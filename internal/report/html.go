package report

import (
	"html/template"
	"io"

	"github.com/gatehouse/gatehouse/internal/model"
)

// HTML writes a self-contained, offline HTML report for a run to w — a single
// file with inline CSS and no external assets, suitable for sharing or
// archiving in an evidence bundle (plan §10).
func HTML(w io.Writer, run model.Run, deny, warn []string) error {
	return htmlTmpl.Execute(w, map[string]any{
		"Run":  run,
		"Deny": deny,
		"Warn": warn,
	})
}

var htmlTmpl = template.Must(template.New("report").Funcs(template.FuncMap{
	"sev": func(s model.Severity) string { return s.String() },
}).Parse(`<!doctype html><html><head><meta charset="utf-8">
<title>Gatehouse report — {{.Run.ID}}</title>
<style>
body{font:14px/1.5 system-ui,sans-serif;margin:2rem;max-width:1000px;color:#1a1a1a}
h1{font-size:1.4rem}h2{font-size:1.05rem;margin-top:1.6rem}
table{border-collapse:collapse;width:100%}td,th{text-align:left;padding:.4rem .6rem;border-bottom:1px solid #e3e3e3;vertical-align:top}
.verdict{display:inline-block;padding:.15rem .6rem;border-radius:999px;font-weight:700}
.pass{background:#d7f0dd;color:#137333}.warn{background:#fdecc8;color:#8a5a00}.fail{background:#fbd9d7;color:#c5221f}
code{font-family:ui-monospace,monospace}.muted{color:#777}
.sev-critical{color:#b1060f;font-weight:700}.sev-high{color:#d1434b;font-weight:600}.sev-medium{color:#b06000}.sev-low{color:#5f6b7a}
</style></head><body>
<h1>Gatehouse report <code>{{.Run.ID}}</code></h1>
<p><span class="verdict {{.Run.Verdict}}">{{.Run.Verdict}}</span>
 &nbsp;{{.Run.RepoPath}} · {{.Run.Context}} · {{.Run.Ref}}</p>
{{if .Deny}}<h2>Blocking</h2><ul>{{range .Deny}}<li>{{.}}</li>{{end}}</ul>{{end}}
{{if .Warn}}<h2>Warnings</h2><ul>{{range .Warn}}<li>{{.}}</li>{{end}}</ul>{{end}}

<h2>Findings ({{len .Run.Findings}})</h2>
<table><tr><th>Status</th><th>Severity</th><th>Rule</th><th>Location</th><th>Message</th></tr>
{{range .Run.Findings}}<tr>
<td>{{.Status}}{{if .WaiverID}} <span class="muted">(waived)</span>{{end}}</td>
<td class="sev-{{sev .Severity}}">{{sev .Severity}}{{if .KEV}} · KEV{{end}}</td>
<td><code>{{.RuleID}}</code><br><span class="muted">{{.Tool}}</span></td>
<td><code>{{.Path}}:{{.StartLine}}</code></td>
<td>{{.Message}}</td>
</tr>{{end}}
</table>

{{if .Run.Tests}}<h2>Tests ({{len .Run.Tests}})</h2>
<table><tr><th>Suite</th><th>Name</th><th>Status</th><th>Flaky</th></tr>
{{range .Run.Tests}}<tr><td>{{.Suite}}</td><td><code>{{.Name}}</code></td><td>{{.Status}}{{if .Quarantined}} (quarantined){{end}}</td><td>{{if .Flaky}}flaky{{else}}—{{end}}</td></tr>{{end}}
</table>{{end}}

{{if .Run.SBOM}}<h2>Components ({{len .Run.SBOM}})</h2>
<table><tr><th>Name</th><th>Version</th><th>Licence</th></tr>
{{range .Run.SBOM}}<tr><td>{{.Name}}</td><td><code>{{.Version}}</code></td><td>{{.License}}</td></tr>{{end}}
</table>{{end}}

<p class="muted">Generated by Gatehouse · tree {{.Run.TreeHash}}</p>
</body></html>`))
